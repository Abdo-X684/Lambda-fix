#!/usr/bin/env python3
"""Generate the merged BHL + OP4 network delta used by the mod folder.

The engine reads one ``delta.lst`` for both client and server. The pure OP4
delta drops two BugfixedHL fixes, while BHL's delta lacks the OP4-only
``iuser4`` CTF-item field. This tool starts from the pinned BHL delta and
applies only the OP4 protocol differences required by a full OP4 server:

* ``clientdata_t.m_iId`` is widened from 5 to 6 bits (OP4 has 64 weapon IDs).
* ``clientdata_t.iuser4`` is added with OP4's 8-bit encoding for CTF items.

BHL's wider ``health`` (11 bits) and ``eflags`` (2 bits, EFLAG_FLESH_SOUND)
are deliberately retained. No map, model, sound or music file is invented.
"""
from __future__ import annotations

import argparse
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
BHL_DELTA = ROOT / ".cache/upstreams/bugfixhl/gamedir/delta.lst"
OP4_DELTA = ROOT / ".cache/upstreams/op4/network/delta.lst"
DEFAULT_OUT = ROOT / "data/delta.lst"

BHL_M_IID = "\tDEFINE_DELTA( m_iId, DT_INTEGER, 5, 1.0 ),"
OP4_M_IID = "\tDEFINE_DELTA( m_iId, DT_INTEGER, 6, 1.0 ),"
BHL_IUSER2 = "\tDEFINE_DELTA( iuser2, DT_INTEGER, 6, 1.0 ),"
OP4_IUSER4 = "\tDEFINE_DELTA( iuser4, DT_INTEGER, 8, 1.0 ),"


def build() -> str:
    bhl = BHL_DELTA.read_text(encoding="utf-8", errors="surrogateescape")
    op4 = OP4_DELTA.read_text(encoding="utf-8", errors="surrogateescape")

    if BHL_M_IID not in bhl or BHL_IUSER2 not in bhl:
        raise SystemExit("pinned BHL delta no longer has the expected anchors")
    if OP4_M_IID not in op4 or OP4_IUSER4 not in op4:
        raise SystemExit("pinned OP4 delta no longer has the expected fields")

    merged = bhl.replace(BHL_M_IID, OP4_M_IID, 1)
    merged = merged.replace(BHL_IUSER2, BHL_IUSER2 + "\n" + OP4_IUSER4, 1)

    checks = {
        "OP4 6-bit m_iId": OP4_M_IID,
        "OP4 iuser4 CTF items": OP4_IUSER4,
        "BHL 11-bit health": "\tDEFINE_DELTA( health, DT_SIGNED | DT_FLOAT, 11, 1.0 ),",
        "BHL 2-bit eflags": "\tDEFINE_DELTA( eflags, DT_INTEGER, 2, 1.0 ),",
    }
    for name, marker in checks.items():
        if marker not in merged:
            raise SystemExit(f"merged delta is missing {name}")
    if "DEFINE_DELTA( iuser4" in merged and merged.count("DEFINE_DELTA( iuser4") != 1:
        raise SystemExit("merged delta has duplicate iuser4 entries")

    header = (
        "// MERGED BHL + OP4 delta.lst\n"
        "// BHL base: tmp64/BugfixedHL-Rebased @ 4d32095e3c33d5ca60809d9c51f8aafe51c0a521\n"
        "// OP4 protocol: twhl-community/halflife-op4-updated @ 5368be7f8eba14b05236c7c52ad5f6b11fd95e55\n"
        "// Preserves BHL's 11-bit health / 2-bit eflags and adds OP4's 6-bit m_iId / 8-bit iuser4.\n"
        "// Generated by tools/make_merged_delta.py -- do not hand-edit.\n"
    )
    return header + merged


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", type=Path, default=DEFAULT_OUT)
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args()
    out = a.out if a.out.is_absolute() else ROOT / a.out
    text = build()
    if a.check:
        if not out.is_file() or out.read_text(encoding="utf-8", errors="surrogateescape") != text:
            raise SystemExit(f"{out} is not in sync with the pinned upstreams")
        print(f"== MERGED DELTA OK: {out.relative_to(ROOT)} ==")
    else:
        out.write_text(text, encoding="utf-8", errors="surrogateescape")
        print(f"wrote {out.relative_to(ROOT)} ({len(text.encode('utf-8', 'surrogateescape'))} bytes)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
