#!/usr/bin/env python3
"""Generate ``src/speedrun/sr_route_data.h`` from ``data/op4_route.json``.

Keeping the route in one JSON file means the C++ core, the cfg comments, the
dashboard and the tests can never disagree about the OP4 chapter order.
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))

from merge.configgen import load_route  # noqa: E402

HEADER = ROOT / "src" / "speedrun" / "sr_route_data.h"


def _cstr(value: str) -> str:
    return '"' + value.replace("\\", "\\\\").replace('"', '\\"') + '"'


def expected_header(root: Path = ROOT) -> str:
    route = load_route(root)
    lines = [
        "// Generated by tools/gen_route_header.py from data/op4_route.json.",
        "// DO NOT EDIT. Regenerate with: python3 tools/gen_route_header.py --write",
        "#pragma once",
        '#include "sr_core.h"',
        "",
        "namespace sr {",
        "namespace route_data {",
        "",
    ]
    for ch in route["chapters"]:
        var = f"kMaps_{ch['id']}"
        lines.append(f"static const char* const {var}[] = {{")
        for name in ch["maps"]:
            lines.append(f"    {_cstr(name)},")
        lines.append("};")
        lines.append("")
    lines.append("static const ChapterData kChapters[] = {")
    for ch in route["chapters"]:
        lines.append(
            "    { " + ", ".join(
                [
                    _cstr(ch["id"]), _cstr(ch["name"]), _cstr(ch["name_ar"]),
                    f"kMaps_{ch['id']}", str(len(ch["maps"])),
                ]
            ) + " },"
        )
    lines += [
        "};",
        f"static const int kChapterCount = {len(route['chapters'])};",
        "",
        "static const char* const kBootCampMaps[] = {",
    ]
    for name in route["boot_camp"]["maps"]:
        lines.append(f"    {_cstr(name)},")
    lines += [
        "};",
        f"static const int kBootCampMapCount = {len(route['boot_camp']['maps'])};",
        "",
        "}  // namespace route_data",
        "}  // namespace sr",
        "",
    ]
    return "\n".join(lines)


def check_header(root: Path = ROOT) -> list[str]:
    path = root / "src" / "speedrun" / "sr_route_data.h"
    if not path.is_file():
        return [f"missing generated header: {path} (run tools/gen_route_header.py --write)"]
    if path.read_text(encoding="utf-8") != expected_header(root):
        return ["src/speedrun/sr_route_data.h is out of date with data/op4_route.json"]
    return []


def main(argv: list[str] | None = None) -> int:
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument("--write", action="store_true", help="write the generated header")
    p.add_argument("--check", action="store_true", help="fail if the header is out of date")
    args = p.parse_args(argv)
    text = expected_header()
    if args.write or not HEADER.is_file():
        HEADER.write_text(text, encoding="utf-8")
        print(f"wrote {HEADER.relative_to(ROOT)}")
        return 0
    problems = check_header()
    if problems:
        for problem in problems:
            print(f"  ! {problem}", file=sys.stderr)
        return 1
    print("src/speedrun/sr_route_data.h is in sync with data/op4_route.json")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
