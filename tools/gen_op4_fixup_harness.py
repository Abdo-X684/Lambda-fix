    for path, sig in glue_bodies:
        body = extract(path, sig)
        chunks.append(f"\n/* from {path.relative_to(ROOT)} : {sig} */\n{body}\n")
        print(f"  extracted {sig:38s} {len(body):5d} bytes")
    chunks.append(EPILOGUE)
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(chunks))
    print(f"  wrote {OUT.relative_to(ROOT)}")
    return 0


