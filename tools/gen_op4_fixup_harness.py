def extract(path: Path, signature: str) -> str:
    """Return the full function definition (signature + brace-matched body)."""
    text = path.read_text()
    m = re.search(r"^[^\n;{}]*\b" + re.escape(signature) + r"\b[^;{}]*\{",
                  text, re.M | re.S)
    if not m:
        raise SystemExit(f"cannot find function {signature!r} in {path}")
    start = m.start()
    while start > 0 and text[start - 1] != "\n":
        start -= 1
    brace = text.index("{", m.start())
    depth = 0
    for i in range(brace, len(text)):
        if text[i] == "{":
            depth += 1
        elif text[i] == "}":
            depth -= 1
            if depth == 0:
                return text[start:i + 1].strip()
    raise SystemExit(f"unbalanced braces in {signature}")


