"""Deterministic merge report (JSON + human-readable Markdown)."""

from __future__ import annotations

import hashlib
from pathlib import Path
from typing import Any

SKIP_IN_HASH = {"MERGE_REPORT.json", "MERGE_REPORT.md"}


def compute_tree_hash(root: Path) -> tuple[str, int]:
    """Hash every file by (relative path, bytes), sorted for reproducibility."""
    digest = hashlib.sha256()
    count = 0
    for path in sorted(p for p in root.rglob("*") if p.is_file()):
        rel = path.relative_to(root).as_posix()
        if rel in SKIP_IN_HASH:
            continue
        digest.update(rel.encode("utf-8"))
        digest.update(b"\0")
        digest.update(path.read_bytes())
        digest.update(b"\0")
        count += 1
    return digest.hexdigest(), count


def render_markdown(report: dict[str, Any]) -> str:
    s = report["summary"]
    lines: list[str] = [
        f"# Merge report - {report['project']}",
        "",
        f"- Mode: `{report['mode']}` (fixtures are offline, `upstream` uses pinned SDKs)",
        f"- Generated: {report['started_at']}",
        f"- Target SDK: `{report['target']}`",
        f"- Files in merged tree: **{report['tree_files']}**",
        f"- Tree SHA-256: `{report['tree_hash']}`",
        "",
        "## Upstreams (pinned + checksum verified)",
        "",
        "| name | role | repo | commit | license |",
        "| --- | --- | --- | --- | --- |",
    ]
    for u in report["upstreams"]:
        lines.append(
            f"| `{u['name']}` | {u['role']} | {u['repo']} | `{u['ref'][:12]}` | {u['license']} |"
        )
    lines += [
        "",
        "## Rule results",
        "",
        "| rule | action | path | status |",
        "| --- | --- | --- | --- |",
    ]
    for f in report["files"]:
        lines.append(f"| `{f['rule']}` | {f['action']} | `{f['path']}` | **{f['status']}** |")
    lines += [
        "",
        "## Summary",
        "",
        "| metric | value |",
        "| --- | --- |",
    ]
    for key, value in s.items():
        lines.append(f"| {key} | {value} |")

    if not report["conflicts"] and not report["manual_port"]:
        lines += ["", "## ✅ No outstanding conflicts or deferred ports", "",
                  "Every divergence resolved: either an OP4-native equivalence was verified",
                  "(see the audit table) or a curated fix was injected and compiled.", ""]
    if report.get("audits"):
        lines += ["", "## Equivalence audits (BugfixedHL fix -> OP4-native implementation)", ""]
        for a in report["audits"]:
            lines.append(f"- `{a['path']}` — **{a['verdict']}** ({a['feature']}) — {a['evidence']}")
            for c in a["checks"]:
                lines.append(f"    - [{'x' if c['ok'] else ' '}] {c['meaning']} (found {c['found']}, need {c['min']})")
    if report["conflicts"]:
        lines += ["", "## Conflicts (quarantined, never written into buildable sources)", ""]
        for c in report["conflicts"]:
            lines.append(f"- `{c['path']}` - {c['blocks']} conflicting hunk(s) -> `{c.get('quarantine', c['path'])}`")
    if report["manual_port"]:
        lines += ["", "## Deferred manual ports", ""]
        for m in report["manual_port"]:
            lines.append(f"- `{m['path']}` ({m['feature']}): {m['reason']}")
    if report["warnings"]:
        lines += ["", "## Warnings", ""]
        lines.extend(f"- {w}" for w in report["warnings"])
    if report["build_files"]:
        lines += ["", "## Build files patched", ""]
        for b in report["build_files"]:
            lines.append(f"- `{b['file']}`: {', '.join(b['added']) or 'already up to date'}")
    lines += [
        "",
        "## Status legend",
        "",
        "- `audited`: donor fix already present natively in OP4, machine-verified",
        "- `merged` / `unchanged`: 3-way merge applied cleanly",
        "- `conflict`: conflicting hunks quarantined for a human to resolve",
        "- `deferred`: OP4 version kept; donor rewrite needs a manual port",
        "- `added`, `injected`, `generated`, `patched`: files added/changed by this kit",
        "- `anchor_drift`, `missing`, `error`: upstream changed, review the rule",
        "",
        "Generated by `python3 -m merge.cli run`. Do not edit by hand.",
        "",
    ]
    return "\n".join(lines)
